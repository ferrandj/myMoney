"""Generate src/adapters/generic/ofx_tables.rs: the data the OFX reader needs from Python's standard library and bs4.

- the HTML entities BeautifulSoup resolves (bs4.dammit.EntitySubstitution.HTML_ENTITY_TO_CHARACTER),
- its Windows-1252 table for numeric references 0x80-0x9f and the noncharacters it keeps as they are,
- every codec `codecs.lookup("cp" + charset)` can find, by normalized name, with the decoding table of the single-byte ones.

Run from the repository root: python3 tools/gen_ofx_tables.py
"""

import codecs
import importlib
import encodings
import encodings.aliases
import pkgutil

from bs4.dammit import EntitySubstitution, UnicodeDammit


def rs(s: str) -> str:
    return '"' + "".join(c if c.isprintable() and c not in '"\\' else "\\u{%x}" % ord(c) for c in s) + '"'


out = ["// Generated by tools/gen_ofx_tables.py: do not edit.", "#![allow(clippy::all)]", ""]

entities = sorted(EntitySubstitution.HTML_ENTITY_TO_CHARACTER.items())
out.append(f"pub static HTML_ENTITIES: [(&str, &str); {len(entities)}] = [")
out += [f"    ({rs(k)}, {rs(v)})," for k, v in entities]
out.append("];")

w = sorted((k, v) for k, v in UnicodeDammit.WINDOWS_1252_TO_UTF8.items() if 0x80 <= k <= 0x9f)
out.append(f"pub static WINDOWS_1252: [(u32, &str); {len(w)}] = [")
out += [f"    ({k}, {rs(v.decode('utf8'))})," for k, v in w]
out.append("];")
nc = sorted(UnicodeDammit.ENUMERATED_NONCHARACTERS)
out.append(f"pub static NONCHARACTERS: [u32; {len(nc)}] = [{', '.join(str(x) for x in nc)}];")

# Codec names: every alias and every module of the encodings package, as encodings.search_function normalizes them.
names = set(encodings.aliases.aliases) | {m.name for m in pkgutil.iter_modules(encodings.__path__)}
tables = {}
kinds = {}
for name in sorted(names):
    try:
        info = codecs.lookup(name)
    except LookupError:
        continue
    canonical = info.name
    if canonical in ("utf-8", "ascii", "latin-1", "iso8859-1"):
        kinds[name] = {"utf-8": "Utf8", "ascii": "Ascii"}.get(canonical, "Latin1")
        continue
    # Single-byte codecs are the charmap ones: their module has a decoding table.
    mod_name = getattr(info.decode, "__module__", None) or ""
    module = importlib.import_module(mod_name) if mod_name.startswith("encodings.") else None
    if module is None or not hasattr(module, "decoding_table"):
        continue
    table = []
    for b in range(256):
        try:
            table.append(bytes([b]).decode(canonical))
        except UnicodeDecodeError:
            table.append(None)
    tables.setdefault(canonical, table)
    kinds[name] = canonical

ids = sorted(tables)
out.append(f"pub static SINGLE_BYTE: [(&str, [u32; 256]); {len(ids)}] = [")
for c in ids:
    vals = ", ".join(str(ord(x)) if x is not None else "0xFFFFFFFF" for x in tables[c])
    out.append(f"    ({rs(c)}, [{vals}]),")
out.append("];")
out.append(f"pub static CODECS: [(&str, &str); {len(kinds)}] = [")
out += [f"    ({rs(k)}, {rs(v)})," for k, v in sorted(kinds.items())]
out.append("];")

open("src/adapters/generic/ofx_tables.rs", "w").write("\n".join(out) + "\n")
print(len(entities), "entities,", len(ids), "single-byte codecs,", len(kinds), "names")

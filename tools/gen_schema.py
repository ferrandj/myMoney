"""Generate src/schema.rs from the Python models: DDL in SQLAlchemy's own order and text, and every column with its
type and nullability, so the Rust version creates and reads exactly the same database."""

import sys

from sqlalchemy import JSON, Boolean, Date, DateTime, Integer, create_engine, event

sys.path.insert(0, "python")
from mymoney.models import Base, DecimalText  # noqa: E402


def rust(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


e = create_engine("sqlite://")
stmts = []


@event.listens_for(e, "before_cursor_execute")
def capture(conn, cursor, statement, *a):
    stmts.append(statement)


Base.metadata.create_all(e)
plan = []
for s in stmts:
    st = s.strip()
    if st.startswith("CREATE TABLE"):
        plan.append([st.split()[2], s, []])
    elif st.startswith("CREATE INDEX"):
        plan[-1][2].append(s)

out = ["// Generated by tools/gen_schema.py from the Python models: do not edit.", ""]
out.append("/// (table, CREATE TABLE statement, CREATE INDEX statements) in SQLAlchemy's creation order.")
out.append("pub static TABLES: &[(&str, &str, &[&str])] = &[")
for name, ddl, idx in plan:
    out.append("    (" + rust(name) + ", " + rust(ddl) + ", &[" + ", ".join(rust(i) for i in idx) + "]),")
out.append("];")
out.append("")
out.append("/// (table, column, SQL type, nullable) of every column, for the light schema upgrade.")
out.append("pub static COLUMNS: &[(&str, &str, &str, bool)] = &[")
for t in Base.metadata.sorted_tables:
    for c in t.columns:
        out.append(f"    ({rust(t.name)}, {rust(c.name)}, {rust(c.type.compile(dialect=e.dialect))}, {'true' if c.nullable else 'false'}),")
out.append("];")
open("src/schema.rs", "w").write("\n".join(out) + "\n")
print("tables", len(plan))

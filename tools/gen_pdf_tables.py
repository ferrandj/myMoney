"""Generate src/pdf/tables.rs from pdfminer's own data, so the Rust reader uses exactly the same tables:
standard encodings, the Adobe glyph list and the metrics of the 14 standard fonts."""

import json
import sys

from pdfminer.encodingdb import EncodingDB
from pdfminer.fontmetrics import FONT_METRICS
from pdfminer.glyphlist import glyphname2unicode


def rs(s: str) -> str:
    return json.dumps(s, ensure_ascii=False).replace("\\u", "\\u").replace("\x7f", "\\u{7f}")


def rust_str(s: str) -> str:
    out = '"'
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out += '\\"'
        elif ch == "\\":
            out += "\\\\"
        elif o < 0x20 or o == 0x7F or 0xD800 <= o <= 0xDFFF or o > 0x7E:
            out += "\\u{%x}" % o
        else:
            out += ch
    return out + '"'


lines = ["// Generated by tools/gen_pdf_tables.py from pdfminer's data: do not edit.", "#![allow(clippy::all)]", ""]
for name, table in (("STD", EncodingDB.std2unicode), ("MAC", EncodingDB.mac2unicode), ("WIN", EncodingDB.win2unicode), ("PDF", EncodingDB.pdf2unicode)):
    lines.append(f"pub static {name}_ENCODING: &[(u32, &str)] = &[")
    for cid in sorted(table):
        lines.append(f"    ({cid}, {rust_str(table[cid])}),")
    lines.append("];")
lines.append("pub static GLYPHLIST: &[(&str, &str)] = &[")
for name in sorted(glyphname2unicode):
    lines.append(f"    ({rust_str(name)}, {rust_str(glyphname2unicode[name])}),")
lines.append("];")
lines.append("pub struct StdFont { pub name: &'static str, pub flags: i64, pub ascent: f64, pub descent: f64, pub italic_angle: f64, pub bbox: [f64; 4], pub widths: &'static [(&'static str, f64)] }")
lines.append("pub static STD_FONTS: &[StdFont] = &[")
for fname in sorted(FONT_METRICS):
    desc, widths = FONT_METRICS[fname]
    assert set(desc) <= {"FontName", "Descent", "FontBBox", "FontWeight", "CapHeight", "ItalicAngle", "Ascent", "Flags", "StemV", "XHeight", "StemH", "CharSet", "FontFamily", "Leading", "MissingWidth"}, desc.keys()
    assert "Leading" not in desc and "MissingWidth" not in desc
    bbox = desc.get("FontBBox", (0, 0, 0, 0))
    ws = ", ".join(f"({rust_str(k)}, {float(v)!r})" for k, v in sorted(widths.items()))
    lines.append(
        f"    StdFont {{ name: {rust_str(fname)}, flags: {int(desc.get('Flags', 0))}, ascent: {float(desc.get('Ascent', 0))!r}, "
        f"descent: {float(desc.get('Descent', 0))!r}, italic_angle: {float(desc.get('ItalicAngle', 0))!r}, "
        f"bbox: [{', '.join(repr(float(x)) for x in bbox)}], widths: &[{ws}] }},"
    )
lines.append("];")
open(sys.argv[1], "w", encoding="utf-8").write("\n".join(lines) + "\n")
